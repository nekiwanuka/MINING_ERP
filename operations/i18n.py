for language, phrases in EXTRA_TRANSLATIONS.items():
    TRANSLATIONS.setdefault(language, {}).update(phrases)


def normalize_language(language):
    return language if language in {"en", "fr", "zh"} else "en"


def translate_mixed_text(text, language="en"):
    language = normalize_language(language)
    text = str(text)
    if language == "en":
        return " ".join(text.split())
    translations = TRANSLATIONS.get(language, {})
    translated = " ".join(text.split())
    for key in sorted(translations, key=len, reverse=True):
        if len(key.strip()) < 2:
            continue
        replacement = translations[key]
        if re.fullmatch(r"[A-Za-z][A-Za-z0-9 /().,-]*", key):
            translated = re.sub(
                rf"(?<![A-Za-z0-9]){re.escape(key)}(?![A-Za-z0-9])",
                replacement,
                translated,
                flags=re.IGNORECASE,
            )
        else:
            translated = re.sub(
                re.escape(key), replacement, translated, flags=re.IGNORECASE
            )
    return translated


def translate(text, language="en"):
    language = normalize_language(language)
    text = " ".join(str(text).split())
    if language == "en":
        return text
    return TRANSLATIONS.get(language, {}).get(
        text, translate_mixed_text(text, language)
    )
